-- =====================================================================
-- Лаба 2 : SQL-версія телеметрії автопарку (еквівалент документа MongoDB)
-- Один документ Mongo  ->  3 таблиці PostgreSQL:
--   telemetry_points  (ядро: координати, швидкість, пальне)         1
--   telemetry_engine  (вкладений об'єкт engine {...}, може бути відсутній) 0..1
--   telemetry_dtc     (масив dtc_codes [...])                       0..N
-- Запускати у базі fleet (після лаби 1 або окремо - залежностей немає).
-- vehicle_id - ЛОГІЧНЕ посилання на vehicles (без FK: у Mongo FK немає, тест чесний).
-- =====================================================================

DROP VIEW  IF EXISTS vw_telemetry_full;
DROP TABLE IF EXISTS telemetry_dtc, telemetry_engine, telemetry_points CASCADE;

CREATE TABLE telemetry_points (
    point_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id     BIGINT           NOT NULL,
    ts             TIMESTAMPTZ      NOT NULL,
    lat            DOUBLE PRECISION NOT NULL,
    lon            DOUBLE PRECISION NOT NULL,
    speed_kmh      DOUBLE PRECISION,
    fuel_level_pct DOUBLE PRECISION
);

CREATE TABLE telemetry_engine (
    point_id       BIGINT PRIMARY KEY REFERENCES telemetry_points(point_id),
    rpm            INT,
    coolant_temp_c DOUBLE PRECISION,
    load_pct       DOUBLE PRECISION
);

CREATE TABLE telemetry_dtc (
    point_id BIGINT      NOT NULL REFERENCES telemetry_points(point_id),
    dtc_code VARCHAR(8)  NOT NULL
);

-- Індекси (ті самі за змістом, що й у MongoDB)
CREATE INDEX ix_tp_vehicle_ts ON telemetry_points (vehicle_id, ts DESC);  -- ~ {vehicle_id:1, ts:-1}
CREATE INDEX ix_td_code       ON telemetry_dtc (dtc_code);                -- ~ multikey {dtc_codes:1}
CREATE INDEX ix_td_point      ON telemetry_dtc (point_id);                -- для JOIN

-- "Склеєний документ": відновлення повної картини з 3 таблиць
CREATE VIEW vw_telemetry_full AS
SELECT p.point_id, p.vehicle_id, p.ts, p.lat, p.lon, p.speed_kmh, p.fuel_level_pct,
       e.rpm, e.coolant_temp_c, e.load_pct,
       COALESCE((SELECT array_agg(d.dtc_code) FROM telemetry_dtc d WHERE d.point_id = p.point_id),
                '{}') AS dtc_codes
FROM telemetry_points p
LEFT JOIN telemetry_engine e ON e.point_id = p.point_id;

-- Додавання одного повідомлення від пристрою (атомарно у 3 таблиці)
CREATE OR REPLACE FUNCTION sp_telemetry_add(
    p_vehicle_id BIGINT, p_ts TIMESTAMPTZ, p_lat DOUBLE PRECISION, p_lon DOUBLE PRECISION,
    p_speed DOUBLE PRECISION, p_fuel DOUBLE PRECISION,
    p_rpm INT, p_temp DOUBLE PRECISION, p_load DOUBLE PRECISION, p_dtc TEXT[])
RETURNS BIGINT LANGUAGE plpgsql AS $$
DECLARE v_id BIGINT;
BEGIN
    INSERT INTO telemetry_points(vehicle_id, ts, lat, lon, speed_kmh, fuel_level_pct)
    VALUES (p_vehicle_id, p_ts, p_lat, p_lon, p_speed, p_fuel)
    RETURNING point_id INTO v_id;

    IF p_rpm IS NOT NULL OR p_temp IS NOT NULL OR p_load IS NOT NULL THEN
        INSERT INTO telemetry_engine(point_id, rpm, coolant_temp_c, load_pct)
        VALUES (v_id, p_rpm, p_temp, p_load);
    END IF;

    IF p_dtc IS NOT NULL THEN
        INSERT INTO telemetry_dtc(point_id, dtc_code) SELECT v_id, unnest(p_dtc);
    END IF;
    RETURN v_id;
END $$;

-- Приклад
SELECT sp_telemetry_add(1, now(), 50.45, 30.52, 63.5, 71.2, 2100, 92.5, 40.0, ARRAY['P0300']);
SELECT * FROM vw_telemetry_full ORDER BY ts DESC LIMIT 5;
