using System.Diagnostics;
using System.Text;
using MongoDB.Bson;
using MongoDB.Driver;
using Npgsql;
using NpgsqlTypes;

namespace Fleet.Bench;

public record Engine(int Rpm, double Temp, double Load);
public record Point(long VehicleId, DateTime Ts, double Lat, double Lon, double Speed, double Fuel,
                    Engine? Engine, string[] Dtc);

public static class Program
{
    const string PgCs = "Host=localhost;Port=5432;Database=fleet;Username=postgres;Password=**";
    const string MongoCs = "mongodb://localhost:27017";

    const int Vehicles = 100;        
    const int PointsPerVehicle = 5_000; 
    const int Reps = 30;                
    const int AggReps = 5;            
    const int SingleInserts = 2_000;    
    const int WindowPoints = 720;       

    static readonly DateTime Start = new(2026, 1, 1, 0, 0, 0, DateTimeKind.Utc);
    static readonly string[] Codes = { "P0300", "P0171", "P0420", "P0101", "U0100" };
    static readonly List<string[]> Rows = new();

    const string SqlSetup = @"
DROP TABLE IF EXISTS telemetry_dtc, telemetry_engine, telemetry_points CASCADE;
CREATE TABLE telemetry_points (
    point_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT NOT NULL, ts TIMESTAMPTZ NOT NULL,
    lat DOUBLE PRECISION NOT NULL, lon DOUBLE PRECISION NOT NULL,
    speed_kmh DOUBLE PRECISION, fuel_level_pct DOUBLE PRECISION);
CREATE TABLE telemetry_engine (
    point_id BIGINT PRIMARY KEY REFERENCES telemetry_points(point_id),
    rpm INT, coolant_temp_c DOUBLE PRECISION, load_pct DOUBLE PRECISION);
CREATE TABLE telemetry_dtc (
    point_id BIGINT NOT NULL REFERENCES telemetry_points(point_id),
    dtc_code VARCHAR(8) NOT NULL);";

    const string SqlIndexes = @"
CREATE INDEX ix_tp_vehicle_ts ON telemetry_points (vehicle_id, ts DESC);
CREATE INDEX ix_td_code ON telemetry_dtc (dtc_code);
CREATE INDEX ix_td_point ON telemetry_dtc (point_id);
ANALYZE telemetry_points; ANALYZE telemetry_engine; ANALYZE telemetry_dtc;";

    const string FullCols =
        "p.point_id, p.vehicle_id, p.ts, p.lat, p.lon, p.speed_kmh, p.fuel_level_pct, " +
        "e.rpm, e.coolant_temp_c, e.load_pct, " +
        "COALESCE((SELECT array_agg(d.dtc_code) FROM telemetry_dtc d WHERE d.point_id = p.point_id), '{}') AS dtc_codes";

    const string SqlLast50 =
        "SELECT " + FullCols + " FROM (SELECT * FROM telemetry_points WHERE vehicle_id = @v ORDER BY ts DESC LIMIT 50) p " +
        "LEFT JOIN telemetry_engine e ON e.point_id = p.point_id ORDER BY p.ts DESC";

    const string SqlRange =
        "SELECT " + FullCols + " FROM telemetry_points p LEFT JOIN telemetry_engine e ON e.point_id = p.point_id " +
        "WHERE p.vehicle_id = @v AND p.ts >= @a AND p.ts < @b ORDER BY p.ts";

    const string SqlAgg =
        "SELECT p.vehicle_id, AVG(p.speed_kmh), AVG(e.coolant_temp_c), COUNT(*) " +
        "FROM telemetry_points p LEFT JOIN telemetry_engine e ON e.point_id = p.point_id GROUP BY p.vehicle_id";

    const string SqlDtc =
        "SELECT p.vehicle_id, p.ts FROM telemetry_dtc d JOIN telemetry_points p ON p.point_id = d.point_id " +
        "WHERE d.dtc_code = 'P0300'";

    public static async Task Main(string[] args)
    {
        Console.OutputEncoding = Encoding.UTF8;
        if (args.Length > 0 && args[0] == "redis") { await RedisDemo.RunAsync(); return; }

        Console.WriteLine($"Авто: {Vehicles}, точок на авто: {PointsPerVehicle}, всього: {Vehicles * PointsPerVehicle:N0}");

        await using var ds = NpgsqlDataSource.Create(PgCs);
        var mongo = new MongoClient(MongoCs);
        var db = mongo.GetDatabase("fleet_nosql");
        await db.DropCollectionAsync("telemetry");
        var col = db.GetCollection<BsonDocument>("telemetry");
        await ExecPg(ds, SqlSetup);

        Console.WriteLine("Генерація даних...");
        var data = Enumerable.Range(1, Vehicles)
            .Select(v => Generate(v, PointsPerVehicle, Start, v).ToList()).ToList();

        Console.WriteLine("1/7 Масове завантаження...");
        var sw = Stopwatch.StartNew(); await LoadMongo(col, data); var mLoad = sw.Elapsed.TotalMilliseconds;
        sw.Restart();                  await LoadPg(ds, data);     var pLoad = sw.Elapsed.TotalMilliseconds;
        AddOnce("Масове завантаження 500 тис. повідомлень", mLoad, pLoad);

        Console.WriteLine("2/7 Індекси...");
        sw.Restart();
        await col.Indexes.CreateManyAsync(new[]
        {
            new CreateIndexModel<BsonDocument>(Builders<BsonDocument>.IndexKeys.Ascending("vehicle_id").Descending("ts")),
            new CreateIndexModel<BsonDocument>(Builders<BsonDocument>.IndexKeys.Ascending("dtc_codes"))
        });
        var mIdx = sw.Elapsed.TotalMilliseconds;
        sw.Restart(); await ExecPg(ds, SqlIndexes); var pIdx = sw.Elapsed.TotalMilliseconds;
        AddOnce("Побудова індексів", mIdx, pIdx);

        Console.WriteLine("3/7 Одиничні вставки...");
        var extra = Enumerable.Range(0, SingleInserts)
            .Select(i => Generate(1 + i % Vehicles, 1, Start.AddDays(10).AddSeconds(i), 1000 + i).First()).ToList();
        var mIns = new double[SingleInserts];
        for (int i = 0; i < SingleInserts; i++)
        {
            var t = Stopwatch.GetTimestamp();
            await col.InsertOneAsync(ToDoc(extra[i]));
            mIns[i] = Stopwatch.GetElapsedTime(t).TotalMilliseconds;
        }
        var pIns = new double[SingleInserts];
        await using (var conn = await ds.OpenConnectionAsync())
            for (int i = 0; i < SingleInserts; i++)
            {
                var t = Stopwatch.GetTimestamp();
                await InsertPgOne(conn, 10_000_000L + i, extra[i]);
                pIns[i] = Stopwatch.GetElapsedTime(t).TotalMilliseconds;
            }
        AddStats("Одиничний INSERT (1 повідомлення)", mIns, pIns);

        Console.WriteLine("4/7 Останні 50...");
        var fb = Builders<BsonDocument>.Filter;
        var m4 = await Time(Reps, async i =>
            (await col.Find(fb.Eq("vehicle_id", Vid(i))).Sort(Builders<BsonDocument>.Sort.Descending("ts"))
                      .Limit(50).ToListAsync()).Count);
        var p4 = await Time(Reps, i => PgQuery(ds, SqlLast50, ("v", Vid(i))));
        AddStats("Останні 50 повідомлень авто (повний запис)", m4, p4);

        Console.WriteLine("5/7 Діапазон часу...");
        var m5 = await Time(Reps, async i =>
        {
            var (a, b) = Window(i);
            return (await col.Find(fb.And(fb.Eq("vehicle_id", Vid(i)), fb.Gte("ts", a), fb.Lt("ts", b)))
                             .Sort(Builders<BsonDocument>.Sort.Ascending("ts")).ToListAsync()).Count;
        });
        var p5 = await Time(Reps, i => { var (a, b) = Window(i); return PgQuery(ds, SqlRange, ("v", Vid(i)), ("a", a), ("b", b)); });
        AddStats("Діапазон 6 год для авто (~720 записів)", m5, p5);

        Console.WriteLine("6/7 Агрегація...");
        var m6 = await Time(AggReps, async _ =>
            (await col.Aggregate().Group(new BsonDocument
            {
                { "_id", "$vehicle_id" },
                { "avg_speed", new BsonDocument("$avg", "$speed_kmh") },
                { "avg_temp", new BsonDocument("$avg", "$engine.coolant_temp_c") },
                { "n", new BsonDocument("$sum", 1) }
            }).ToListAsync()).Count, warm: 1);
        var p6 = await Time(AggReps, _ => PgQuery(ds, SqlAgg), warm: 1);
        AddStats("Агрегація: середня швидкість/температура по авто (весь набір)", m6, p6);

        Console.WriteLine("7/7 Пошук за DTC...");
        var m7 = await Time(Reps, async _ =>
            (await col.Find(fb.Eq("dtc_codes", "P0300"))
                      .Project(Builders<BsonDocument>.Projection.Include("vehicle_id").Include("ts").Exclude("_id"))
                      .ToListAsync()).Count);
        var p7 = await Time(Reps, _ => PgQuery(ds, SqlDtc));
        AddStats("Пошук усіх записів з кодом P0300", m7, p7);

        var cs = await db.RunCommandAsync<BsonDocument>(new BsonDocument("collStats", "telemetry"));
        double mData = cs["storageSize"].ToDouble() / 1048576.0, mIndex = cs["totalIndexSize"].ToDouble() / 1048576.0;
        double pData, pIndex;
        await using (var conn = await ds.OpenConnectionAsync())
        await using (var cmd = new NpgsqlCommand(
            "SELECT SUM(pg_table_size(t::regclass))::bigint, SUM(pg_indexes_size(t::regclass))::bigint " +
            "FROM unnest(ARRAY['telemetry_points','telemetry_engine','telemetry_dtc']) t", conn))
        await using (var r = await cmd.ExecuteReaderAsync())
        {
            await r.ReadAsync();
            pData = r.GetInt64(0) / 1048576.0; pIndex = r.GetInt64(1) / 1048576.0;
        }

        Report(mData, mIndex, pData, pIndex);
    }

    static IEnumerable<Point> Generate(long vehicleId, int count, DateTime start, int seed)
    {
        var rnd = new Random(seed * 7919 + 13);
        double lat = 50.40 + rnd.NextDouble() * 0.1, lon = 30.45 + rnd.NextDouble() * 0.1;
        double fuel = 60 + rnd.NextDouble() * 40;
        var t = start;
        for (int i = 0; i < count; i++)
        {
            t = t.AddSeconds(30);
            lat += (rnd.NextDouble() - 0.5) * 0.002;
            lon += (rnd.NextDouble() - 0.5) * 0.003;
            fuel -= rnd.NextDouble() * 0.05; if (fuel < 5) fuel = 95;
            double speed = rnd.NextDouble() < 0.2 ? 0 : rnd.NextDouble() * 110;
            Engine? e = rnd.NextDouble() < 0.9
                ? new Engine(rnd.Next(700, 4000), 70 + rnd.NextDouble() * 45, rnd.NextDouble() * 100) : null;
            string[] dtc = rnd.NextDouble() < 0.03 ? new[] { Codes[rnd.Next(Codes.Length)] } : Array.Empty<string>();
            yield return new Point(vehicleId, t, lat, lon, speed, fuel, e, dtc);
        }
    }

    static BsonDocument ToDoc(Point p)
    {
        var doc = new BsonDocument
        {
            { "vehicle_id", p.VehicleId },
            { "ts", p.Ts },
            { "location", new BsonDocument { { "type", "Point" }, { "coordinates", new BsonArray { p.Lon, p.Lat } } } },
            { "speed_kmh", p.Speed },
            { "fuel_level_pct", p.Fuel }
        };
        if (p.Engine is { } e)
            doc["engine"] = new BsonDocument { { "rpm", e.Rpm }, { "coolant_temp_c", e.Temp }, { "load_pct", e.Load } };
        if (p.Dtc.Length > 0)
            doc["dtc_codes"] = new BsonArray(p.Dtc);
        return doc;
    }

    static async Task LoadMongo(IMongoCollection<BsonDocument> col, List<List<Point>> data)
    {
        foreach (var list in data)
            await col.InsertManyAsync(list.Select(ToDoc).ToList(), new InsertManyOptions { IsOrdered = false });
    }

    static async Task ExecPg(NpgsqlDataSource ds, string sql)
    {
        await using var cmd = ds.CreateCommand(sql);
        await cmd.ExecuteNonQueryAsync();
    }

    static async Task LoadPg(NpgsqlDataSource ds, List<List<Point>> data)
    {
        await using var conn = await ds.OpenConnectionAsync();
        await using var tx = await conn.BeginTransactionAsync();
        long baseId = 0;
        foreach (var list in data)
        {
            await using (var w = await conn.BeginBinaryImportAsync(
                "COPY telemetry_points (point_id, vehicle_id, ts, lat, lon, speed_kmh, fuel_level_pct) FROM STDIN (FORMAT BINARY)"))
            {
                for (int k = 0; k < list.Count; k++)
                {
                    var p = list[k];
                    await w.StartRowAsync();
                    await w.WriteAsync(baseId + k + 1, NpgsqlDbType.Bigint);
                    await w.WriteAsync(p.VehicleId, NpgsqlDbType.Bigint);
                    await w.WriteAsync(p.Ts, NpgsqlDbType.TimestampTz);
                    await w.WriteAsync(p.Lat, NpgsqlDbType.Double);
                    await w.WriteAsync(p.Lon, NpgsqlDbType.Double);
                    await w.WriteAsync(p.Speed, NpgsqlDbType.Double);
                    await w.WriteAsync(p.Fuel, NpgsqlDbType.Double);
                }
                await w.CompleteAsync();
            }
            await using (var w = await conn.BeginBinaryImportAsync(
                "COPY telemetry_engine (point_id, rpm, coolant_temp_c, load_pct) FROM STDIN (FORMAT BINARY)"))
            {
                for (int k = 0; k < list.Count; k++)
                {
                    if (list[k].Engine is not { } e) continue;
                    await w.StartRowAsync();
                    await w.WriteAsync(baseId + k + 1, NpgsqlDbType.Bigint);
                    await w.WriteAsync(e.Rpm, NpgsqlDbType.Integer);
                    await w.WriteAsync(e.Temp, NpgsqlDbType.Double);
                    await w.WriteAsync(e.Load, NpgsqlDbType.Double);
                }
                await w.CompleteAsync();
            }
            await using (var w = await conn.BeginBinaryImportAsync(
                "COPY telemetry_dtc (point_id, dtc_code) FROM STDIN (FORMAT BINARY)"))
            {
                for (int k = 0; k < list.Count; k++)
                    foreach (var code in list[k].Dtc)
                    {
                        await w.StartRowAsync();
                        await w.WriteAsync(baseId + k + 1, NpgsqlDbType.Bigint);
                        await w.WriteAsync(code, NpgsqlDbType.Varchar);
                    }
                await w.CompleteAsync();
            }
            baseId += list.Count;
        }
        await tx.CommitAsync();
    }

    static NpgsqlBatchCommand BCmd(string sql, params object[] vals)
    {
        var c = new NpgsqlBatchCommand(sql);
        foreach (var v in vals) c.Parameters.Add(new NpgsqlParameter { Value = v });
        return c;
    }

    static async Task InsertPgOne(NpgsqlConnection conn, long id, Point p)
    {
        await using var batch = new NpgsqlBatch(conn);
        batch.BatchCommands.Add(BCmd(
            "INSERT INTO telemetry_points (point_id, vehicle_id, ts, lat, lon, speed_kmh, fuel_level_pct) VALUES ($1,$2,$3,$4,$5,$6,$7)",
            id, p.VehicleId, p.Ts, p.Lat, p.Lon, p.Speed, p.Fuel));
        if (p.Engine is { } e)
            batch.BatchCommands.Add(BCmd(
                "INSERT INTO telemetry_engine (point_id, rpm, coolant_temp_c, load_pct) VALUES ($1,$2,$3,$4)",
                id, e.Rpm, e.Temp, e.Load));
        foreach (var code in p.Dtc)
            batch.BatchCommands.Add(BCmd("INSERT INTO telemetry_dtc (point_id, dtc_code) VALUES ($1,$2)", id, code));
        await batch.ExecuteNonQueryAsync();
    }

    static async Task<int> PgQuery(NpgsqlDataSource ds, string sql, params (string Name, object Value)[] ps)
    {
        await using var conn = await ds.OpenConnectionAsync();
        await using var cmd = new NpgsqlCommand(sql, conn);
        foreach (var (name, value) in ps) cmd.Parameters.AddWithValue(name, value);
        await using var r = await cmd.ExecuteReaderAsync();
        var buf = new object[r.FieldCount];
        int rows = 0;
        while (await r.ReadAsync()) { r.GetValues(buf); rows++; }
        return rows;
    }

    static long Vid(int i) => 1 + (i * 37 + 11) % Vehicles;       

    static (DateTime a, DateTime b) Window(int i)
    {
        int s = (i * 251) % (PointsPerVehicle - WindowPoints);
        var a = Start.AddSeconds(30 * (s + 1));
        return (a, a.AddSeconds(30 * WindowPoints));
    }

    static async Task<double[]> Time(int reps, Func<int, Task<int>> action, int warm = 3)
    {
        for (int i = 0; i < warm; i++) await action(i);
        var res = new double[reps];
        for (int i = 0; i < reps; i++)
        {
            var t = Stopwatch.GetTimestamp();
            await action(i);
            res[i] = Stopwatch.GetElapsedTime(t).TotalMilliseconds;
        }
        return res;
    }

    static (double Median, double P95) Stat(double[] a)
    {
        var s = a.OrderBy(x => x).ToArray();
        return (s[s.Length / 2], s[(int)Math.Ceiling(s.Length * 0.95) - 1]);
    }

    static string Winner(double m, double p)
    {
        m = Math.Max(m, 0.001); p = Math.Max(p, 0.001);
        return m < p ? $"MongoDB ×{p / m:F1}" : $"PostgreSQL ×{m / p:F1}";
    }

    static void AddOnce(string name, double mMs, double pMs)
        => Rows.Add(new[] { name, $"{mMs:F0}", "—", $"{pMs:F0}", "—", Winner(mMs, pMs) });

    static void AddStats(string name, double[] m, double[] p)
    {
        var (mm, m95) = Stat(m); var (pm, p95) = Stat(p);
        Rows.Add(new[] { name, $"{mm:F2}", $"{m95:F2}", $"{pm:F2}", $"{p95:F2}", Winner(mm, pm) });
    }

    static void Report(double mData, double mIndex, double pData, double pIndex)
    {
        var sb = new StringBuilder();
        sb.AppendLine($"Набір: {Vehicles} авто × {PointsPerVehicle} = {Vehicles * PointsPerVehicle:N0} повідомлень");
        sb.AppendLine();
        sb.AppendLine("| Операція | Mongo медіана, мс | Mongo p95, мс | PG медіана, мс | PG p95, мс | Швидше |");
        sb.AppendLine("|---|---:|---:|---:|---:|---|");
        foreach (var r in Rows) sb.AppendLine("| " + string.Join(" | ", r) + " |");
        sb.AppendLine();
        sb.AppendLine($"Розмір на диску: MongoDB дані {mData:F0} МБ + індекси {mIndex:F0} МБ = {mData + mIndex:F0} МБ");
        sb.AppendLine($"Розмір на диску: PostgreSQL дані {pData:F0} МБ + індекси {pIndex:F0} МБ = {pData + pIndex:F0} МБ");
        Console.WriteLine();
        Console.WriteLine(sb.ToString());
        File.WriteAllText("results.md", sb.ToString(), Encoding.UTF8);
        Console.WriteLine("Збережено у results.md");
    }
}
